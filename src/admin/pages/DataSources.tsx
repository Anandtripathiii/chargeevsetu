import { CardTitle, Container, PageHeader, PageSkeleton, SourceBadge } from '../../components/ui'
import { Completeness } from '../components/Completeness'
import { useData, type SourceEntry, type StateRow, type Summary } from '../../lib/data'
import { fmt, pct } from '../../lib/format'

const ORDER = ['official_national', 'official_chargers', 'official_ev_state', 'annual_registrations', 'osm_chargers', 'ocm', 'merge_chargers',
  'vahan_manual', 'boundaries', 'census', 'worldpop', 'osm_highways', 'osm_substations', 'osm_pois', 'modelled_chargers', 'forecast']

export default function DataSources() {
  const { data: src } = useData<Record<string, SourceEntry>>('sources.json')
  const { data: states } = useData<StateRow[]>('states.json')
  const { data: s } = useData<Summary>('summary.json')
  if (!src || !states || !s) return <PageSkeleton />
  const keys = [...ORDER.filter((k) => src[k]), ...Object.keys(src).filter((k) => !ORDER.includes(k))]

  return (
    <>
      <PageHeader title="Every dataset, with its provenance">
        This table is generated by the pipeline itself (<code>public/data/sources.json</code>), so it always matches the data on the site.
        Each entry lists where the data came from, when it was fetched, its licence, how it was cleaned and what it can't tell us.
      </PageHeader>
      <Container className="space-y-4">
        <Completeness s={s} link={false} />
        <div className="grid gap-3">
          {keys.map((k) => {
            const e = src[k]
            return (
              <article key={k} className="card p-4">
                <div className="flex flex-wrap items-start justify-between gap-2">
                  <h2 className="font-semibold">{e.name}</h2>
                  <div className="flex gap-2 items-center flex-wrap">
                    {e.status && <span className={`chip ${e.status.startsWith('ok') ? 'text-accent' : 'text-warn'}`}>{e.status}</span>}
                    <SourceBadge type={e.source_type} />
                  </div>
                </div>
                <dl className="grid sm:grid-cols-[130px_minmax(0,1fr)] gap-x-4 gap-y-1 text-sm mt-2 [&>dd]:min-w-0 [&>dd]:[overflow-wrap:anywhere]">
                  {e.url && <><dt className="text-muted">Source</dt><dd className="break-words">{e.url.split(' ; ').map((u) => u.startsWith('http') ? <a key={u} href={u.split(' ')[0]} className="text-accent hover:underline block" target="_blank" rel="noreferrer">{u}</a> : <span key={u} className="block">{u}</span>)}</dd></>}
                  <dt className="text-muted">Fetched</dt><dd>{e.fetched}{e.as_of && ` · data as of ${e.as_of}`}</dd>
                  {e.licence && <><dt className="text-muted">Licence</dt><dd>{e.licence}</dd></>}
                  {e.records != null && <><dt className="text-muted">Records</dt><dd className="tnum">{fmt(e.records)}{e.total != null && ` · total ${fmt(e.total)}`}</dd></>}
                  {e.cleaning && <><dt className="text-muted">Cleaning</dt><dd className="text-muted">{e.cleaning}</dd></>}
                  {e.limitations && <><dt className="text-muted">Limitations</dt><dd className="text-muted">{e.limitations}</dd></>}
                </dl>
              </article>
            )
          })}
        </div>

        <div className="card p-4 overflow-x-auto">
          <CardTitle right={<span className="text-xs text-muted">National: {fmt(s.mapped_chargers)} mapped / {fmt(s.public_chargers)} official = {pct(s.mapped_share)}</span>}>Completeness by state: mapped chargers vs the official count</CardTitle>
          <table className="tbl">
            <thead><tr><th>State / UT</th><th className="text-right">Official (Aug 2025)</th><th className="text-right">Estimated 2026</th><th className="text-right">Mapped in OSM</th><th>Completeness</th><th className="text-right">EVs (2023, VAHAN)</th></tr></thead>
            <tbody>{[...states].sort((a, b) => b.official_chargers_2025 - a.official_chargers_2025).map((r) => (
              <tr key={r.state}>
                <td className="font-medium">{r.state}</td>
                <td className="text-right tnum">{fmt(r.official_chargers_2025)}</td>
                <td className="text-right tnum">{fmt(r.chargers)}</td>
                <td className="text-right tnum">{fmt(r.real_chargers)}</td>
                <td><span className="inline-flex items-center gap-2 text-xs tnum"><span className="w-24 h-1.5 rounded-full bg-line overflow-hidden"><span className="block h-full bg-accent" style={{ width: `${Math.min(100, r.completeness)}%` }} /></span>{pct(r.completeness)}</span></td>
                <td className="text-right tnum">{r.ev_stock_2023 != null ? fmt(r.ev_stock_2023) : <span className="text-warn">not reported</span>}</td>
              </tr>
            ))}</tbody>
          </table>
        </div>
      </Container>
    </>
  )
}
